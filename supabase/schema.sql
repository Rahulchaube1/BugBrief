create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  created_at timestamptz not null default now()
);

create table if not exists public.subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  stripe_customer_id text,
  stripe_subscription_id text,
  status text not null default 'inactive' check (status in ('inactive','active','canceled','past_due')),
  updated_at timestamptz not null default now()
);

create table if not exists public.usage_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  input_length integer not null,
  created_at timestamptz not null default now()
);

create table if not exists public.reports (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  input_text text not null,
  output_json jsonb not null,
  created_at timestamptz not null default now()
);

create index if not exists usage_logs_user_created_idx on public.usage_logs(user_id, created_at);
create index if not exists reports_user_created_idx on public.reports(user_id, created_at desc);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles(id,email) values(new.id,new.email)
  on conflict(id) do update set email=excluded.email;
  insert into public.subscriptions(user_id,status) values(new.id,'inactive')
  on conflict(user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.subscriptions enable row level security;
alter table public.usage_logs enable row level security;
alter table public.reports enable row level security;

drop policy if exists profiles_self on public.profiles;
create policy profiles_self on public.profiles for select using (auth.uid()=id);

drop policy if exists subscriptions_self on public.subscriptions;
create policy subscriptions_self on public.subscriptions for select using (auth.uid()=user_id);

drop policy if exists usage_self on public.usage_logs;
create policy usage_self on public.usage_logs for select using (auth.uid()=user_id);

drop policy if exists reports_self on public.reports;
create policy reports_self on public.reports for select using (auth.uid()=user_id);

